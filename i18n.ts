export type Lang = "zh" | "en" | "de" | "es" | "fr" | "ja" | "ko" | "pt" | "ru" | "ar";

const SUPPORTED: Lang[] = ["zh", "en", "de", "es", "fr", "ja", "ko", "pt", "ru", "ar"];

function detectLang(): Lang {
  const raw = (window.localStorage.getItem("language") ?? "en").toLowerCase();
  const code = raw.startsWith("zh") ? "zh" : (raw.slice(0, 2) as Lang);
  return SUPPORTED.includes(code) ? code : "en";
}

