let _lang: Lang | null = null;
let _override: Lang | null = null;

export function setLangOverride(lang: string | null) {
  _override = (lang && SUPPORTED.includes(lang as Lang)) ? (lang as Lang) : null;
  _lang = null; // invalidate auto-detected cache
}

export function getLang(): Lang {
  if (_override !== null) return _override;
  if (!_lang) _lang = detectLang();
  return _lang;
}

export function t(key: keyof UIKeys): string {
  return DICT[getLang()][key];
}

export function isRTL(): boolean {
  return getLang() === "ar";
}
